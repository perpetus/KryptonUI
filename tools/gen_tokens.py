#!/usr/bin/env python3
"""Generate C++ design tokens from design/tokens.json.

Objects become structs, numbers become float, colors (#AARRGGBB or #RRGGBB)
become std::uint32_t, other strings become std::string_view, and arrays become
std::array. An object's "$type" key names its struct, so siblings with the same
shape (light/dark palettes) share one type. Keys starting with "$" are
otherwise ignored.

Usage: gen_tokens.py <tokens.json> <output.hpp>
"""

import json
import re
import sys
from pathlib import Path

COLOR = re.compile(r"^#([0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$")


def snake(name: str) -> str:
    return re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", name).lower()


def camel(name: str) -> str:
    return name[:1].upper() + name[1:]


def color_value(text: str) -> str:
    digits = text[1:]
    if len(digits) == 6:
        digits = "FF" + digits
    return f"0x{digits.upper()}u"


class Generator:
    def __init__(self):
        self.structs = {}  # name -> list[(cpp_type, field)]
        self.order = []

    def type_of(self, key, value):
        if isinstance(value, dict):
            return self.struct(value.get("$type", camel(key)), value)
        if isinstance(value, bool):
            return "bool"
        if isinstance(value, (int, float)):
            return "float"
        if isinstance(value, str):
            return "std::uint32_t" if COLOR.match(value) else "std::string_view"
        if isinstance(value, list):
            if not value:
                raise ValueError(f"{key}: empty arrays have no element type")
            element = self.type_of(key, value[0])
            return f"std::array<{element}, {len(value)}>"
        raise ValueError(f"{key}: unsupported value {value!r}")

    def struct(self, name, obj):
        fields = [(self.type_of(k, v), snake(k)) for k, v in obj.items()
                  if not k.startswith("$")]
        if name in self.structs:
            if self.structs[name] != fields:
                raise ValueError(f"struct {name} is used with two different shapes")
        else:
            self.structs[name] = fields
            self.order.append(name)
        return name

    def literal(self, value):
        if isinstance(value, dict):
            parts = [f".{snake(k)} = {self.literal(v)}"
                     for k, v in value.items() if not k.startswith("$")]
            return "{" + ", ".join(parts) + "}"
        if isinstance(value, bool):
            return "true" if value else "false"
        if isinstance(value, (int, float)):
            return f"{float(value)!r}f"
        if isinstance(value, str):
            if COLOR.match(value):
                return color_value(value)
            escaped = value.replace("\\", "\\\\").replace('"', '\\"')
            return f'std::string_view{{"{escaped}"}}'
        if isinstance(value, list):
            # std::array wraps a native array. Keep that aggregate's braces
            # explicit so arrays of generated structs initialize correctly.
            return "{{" + ", ".join(self.literal(v) for v in value) + "}}"
        raise ValueError(f"unsupported value {value!r}")


def main() -> int:
    source, output = Path(sys.argv[1]), Path(sys.argv[2])
    tokens = json.loads(source.read_text(encoding="utf-8"))
    gen = Generator()
    gen.struct("Tokens", tokens)

    lines = [
        "// Generated by tools/gen_tokens.py from design/tokens.json. Do not edit.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace kr::design {",
        "",
    ]
    # gen.order lists nested structs before the structs that contain them.
    for name in gen.order:
        lines.append(f"struct {name} {{")
        for cpp_type, field in gen.structs[name]:
            lines.append(f"  {cpp_type} {field};")
        lines.append("};")
        lines.append("")
    lines.append(f"inline constexpr Tokens kTokens = {gen.literal(tokens)};")
    lines.append("")
    lines.append("}  // namespace kr::design")
    lines.append("")

    text = "\n".join(lines)
    output.parent.mkdir(parents=True, exist_ok=True)
    if not output.exists() or output.read_text(encoding="utf-8") != text:
        output.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
